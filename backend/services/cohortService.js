import crypto from 'crypto';
import { CohortDefinition, CohortMembership, Trade, WalletTokenPosition } from '../models/index.js';
import { resolveDisplayIdentity } from './identityResolver.js';

function stableId(...parts) {
  return crypto.createHash('sha256').update(parts.map(p => String(p || '')).join('|')).digest('hex');
}

export async function materializeDisplayCohorts(tokenMint) {
  const walletRows = await Trade.distinct('walletAddress', { tokenMint });
  const counts = {};

  for (const wallet of walletRows) {
    const identity = await resolveDisplayIdentity(wallet, tokenMint);
    const key = identity.key;
    if (!counts[key]) {
      counts[key] = {
        identity: key, label: identity.label, category: identity.category,
        walletCount: 0, buyCount: 0, sellCount: 0, netTransactionCount: 0,
        buyVolumeSol: 0, sellVolumeSol: 0, retainedPct: null, coverage: null, qualityStatus: 'partial',
      };
    }
    const bucket = counts[key];
    bucket.walletCount++;

    const buyCount = await Trade.countDocuments({ tokenMint, walletAddress: wallet, side: 'buy' });
    const sellCount = await Trade.countDocuments({ tokenMint, walletAddress: wallet, side: 'sell' });
    const buyAgg = await Trade.aggregate([
      { $match: { tokenMint, walletAddress: wallet, side: 'buy' } },
      { $group: { _id: null, total: { $sum: { $toDouble: { $ifNull: ['$solAmount', '0'] } } } } },
    ]);
    const sellAgg = await Trade.aggregate([
      { $match: { tokenMint, walletAddress: wallet, side: 'sell' } },
      { $group: { _id: null, total: { $sum: { $toDouble: { $ifNull: ['$solAmount', '0'] } } } } },
    ]);
    const buyVolume = buyAgg[0]?.total || 0;
    const sellVolume = sellAgg[0]?.total || 0;
    const position = await WalletTokenPosition.findOne({ tokenMint, walletAddress: wallet }).lean();

    bucket.buyCount += buyCount;
    bucket.sellCount += sellCount;
    bucket.netTransactionCount += buyCount - sellCount;
    bucket.buyVolumeSol += buyVolume;
    bucket.sellVolumeSol += sellVolume;
    if (position?.remainingPct != null) {
      bucket.retainedPct = (bucket.retainedPct || 0) + Number(position.remainingPct);
    }

    const definition = { _id: key, name: identity.label, description: 'Display identity cohort generated by IdentityResolver.', definition: { displayIdentity: identity } };
    await CohortDefinition.findOneAndUpdate({ _id: key }, { $set: definition }, { upsert: true });
    const membershipId = stableId(key, tokenMint, wallet);
    await CohortMembership.findOneAndUpdate(
      { cohortId: key, tokenMint, walletAddress: wallet },
      { $set: { _id: membershipId, evidence: identity } },
      { upsert: true }
    );
  }

  for (const bucket of Object.values(counts)) {
    if (bucket.retainedPct != null && bucket.walletCount) {
      bucket.retainedPct = bucket.retainedPct / bucket.walletCount;
    }
  }
  return Object.values(counts);
}
